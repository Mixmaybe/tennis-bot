BUTTONS = [
    [("🏓 Просто поиграть, без счёта", "g:free")],
    [("📊 Поиграть со счётом", "g:score")],
    [("🏆 Играть в турнире", "g:tour")],
    [("📋 Все команды", "g:cmds")],
]


def guide_kb(current: str | None = None):
    rows = [row for row in BUTTONS if row[0][1] != f"g:{current}"]
    if current:
        rows.append([("⬅️ К разделам", "g:menu")])
    return ikb(rows)


@router.message(Command("help", "guide"))
async def help_cmd(m: Message):
    await m.answer(INTRO, reply_markup=guide_kb())


@router.callback_query(F.data.startswith("g:"))
async def section(c: CallbackQuery):
    key = c.data[2:]
    await c.answer()
    if key == "menu":
        await c.message.edit_text(INTRO, reply_markup=guide_kb())
    else:
        await c.message.edit_text(SECTIONS[key], reply_markup=guide_kb(key))
